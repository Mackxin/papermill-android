KIND = {"c": "choice", "j": "judge", "b": "blank"}
LETTERS = "ABCD"


def main():
    problems = []
    seen = {}
    for i, (g, d, t, k, stem, opts, ans, exp) in enumerate(Q):
        tag = f"#{i} 年级{g} {k} {stem[:16]}"
        if not (1 <= g <= 6):
            problems.append(f"{tag} 年级越界")
        if d not in (1, 2, 3):
            problems.append(f"{tag} 难度越界")
        if k not in KIND:
            problems.append(f"{tag} 题型未知")
        if not stem or not ans:
            problems.append(f"{tag} 题干或答案为空")
        if k == "c":
            if not (3 <= len(opts) <= 4):
                problems.append(f"{tag} 选项数 {len(opts)}")
            if ans not in LETTERS[:len(opts)]:
                problems.append(f"{tag} 答案 {ans} 不在选项范围")
            if len(set(opts)) != len(opts):
                problems.append(f"{tag} 选项重复")
        else:
            if opts:
                problems.append(f"{tag} 非选择题却有选项")
            if k == "j" and ans not in ("√", "×"):
                problems.append(f"{tag} 判断题答案应为 √/×")
        key = (g, re.sub(r"\s+", "", stem))
        if key in seen:
            problems.append(f"{tag} 与 #{seen[key]} 题干重复")
        seen[key] = i
        # 填空题必须留出写答案的位置
        if k == "b" and "（　" not in stem and "（ " not in stem:
            problems.append(f"{tag} 填空题没有留空")

    if problems:
        print("校验未通过：")
        for p in problems:
            print("  -", p)
        sys.exit(1)

    # 用可读的长键：短键（g/d/k/q/o）当初是为了省体积，结果加载器读的是长键，
    # 选项全是空数组，选择题一洗牌就整批丢掉，卷子上一个大题凭空消失。
    # 216 条换成长键只多 2KB，值这个钱。
    out = {"schema": 1, "subject": "SCIENCE", "questions": []}
    for g, d, t, k, stem, opts, ans, exp in Q:
        item = {
            "grade": g,
            "difficulty": d,
            "kind": KIND[k],
            "topic": t,
            "stem": stem,
            "answer": ans,
        }
        if opts:
            item["options"] = opts
        if exp:
            item["explain"] = exp
        out["questions"].append(item)


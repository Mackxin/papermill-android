package com.papermill.app.core.pdf.render

/**
 * 练习纸版式。
 *
 * ============================================================
 * 来源与版权（v0.4.0）
 * ============================================================
 * 「横条书写纸 / 方格纸 / 英文四线三格」这三类**版式思路**参考了
 * github.com/namishu/printables（代码、原创文档、模板设计 MIT）。
 * 该仓库样例 PDF 与其内置字体都没有也不会打进本 App：
 * 这里全部用 Android Canvas 自绘线条，字体走系统回退，
 * 只保留「有哪些版式、每种版式适合练什么」这一层通用设计。
 * 田字格 / 米字格 / 点阵 / 坐标纸属于通行的基础版式，自行编排。
 * 完整 MIT 声明随包放在 assets/licenses/NAMISHU_PRINTABLES_LICENSE.txt。
 */
enum class GridStyle(val label: String, val defaultCell: Float) {
    /** 方格 + 十字虚线，低年级练汉字 */
    TIANZI("田字格", 56f),
    /** 方格 + 十字 + 对角线，练间架结构 */
    MIZI("米字格", 56f),
    /** 四条横线一组，拼音 / 英文书写 */
    FOUR_LINE("四线三格", 36f),
    /** 小方格，数学草稿与画图 */
    SQUARE("方格纸", 20f),
    /** 等距横线，抄写与听写 */
    LINED("横条纸", 28f),
    /** 点阵，控笔练习 */
    DOT_GRID("点阵纸", 20f),
    /** 带坐标轴的方格，初中函数作图 */
    COORDINATE("坐标纸", 20f),
    /**
     * v0.5.0 主题识字卡：拼音在上、田字格在下，一页按词数自动铺满。
     * 只借鉴「拼音在上、汉字在下」这一通用识字卡版式，词表与拼音全部自编重录。
     */
    THEME_CARD("主题识字卡", 72f),

    /**
     * v0.8.0 迷宫纸：递归回溯算法现场生成，每点一次都是新迷宫。
     * 迷宫生成属经典公开算法（深度优先 + 回溯），自行实现、Canvas 自绘，
     * 不使用任何迷宫生成网站的产物。
     */
    MAZE("迷宫纸", 26f),

    // ============================================================
    // v0.15.0 通用纸张模板
    // ============================================================
    // 这一批是「格线本身」的版式（横线、五线谱、康奈尔、拼音田字格…），
    // 属于通行的基础版式，全部用 Canvas 自绘，不引用任何模板站的图片或 PDF。
    // 线距差异不走新样式，直接给 PaperGrid.cell（如横线 6/8/10mm），
    // 只有「结构真的不一样」的才新增一种风格。

    /** 纯白纸：只铺页眉页脚，什么都不画 */
    BLANK("空白纸", 0f),

    /** 康奈尔笔记：左侧线索栏 + 右侧笔记区 + 底部总结区 */
    CORNELL("康奈尔笔记", 26f),

    /** 五线谱：一组五条线，按行铺满 */
    MUSIC("五线谱", 44f),

    /** 拼音田字格：上方拼音三线、下方田字格，小学抄写最常用 */
    PINYIN_TIANZI("拼音田字格", 64f),

    /** 竖式演算格：分列的大格，每格内三条浅横线对齐数位 */
    VERTICAL_CALC("竖式演算格", 120f),

    /** 数轴练习纸：多条带箭头的空白数轴 */
    NUMBER_LINE("数轴练习纸", 60f),

    /** 听写纸：编号 + 横线，写完一个遮一个 */
    DICTATION("听写纸", 34f),

    /** 课程表：节次 × 周一至周五 */
    TIMETABLE("课程表", 0f),

    /** 回宫格：外框 + 内框 + 内部田字，练笔画细节 */
    HUI_GONG("回宫格", 56f),

    /** 九宫格：3×3 细分，练字的比例与重心（传统九宫格没有对角线，对角线是米字格） */
    JIU_GONG("九宫格", 56f),

    /** 错题整理：编号 + 题目 / 错因 / 正解 三段 */
    MISTAKE("错题整理纸", 0f),
}

data class PaperGrid(
    val style: GridStyle,
    /** 格边长 / 行高（pt）；<=0 时用样式默认值 */
    val cell: Float = 0f,
    /** 每页左侧的书写提示（打印在标题下方） */
    val hint: String = "",
    /** 主题识字卡内容：拼音 to 词语；非空时按 [THEME_CARD][GridStyle.THEME_CARD] 版式绘制 */
    val themeCards: List<Pair<String, String>> = emptyList(),
    /** true = 田字格里印浅灰范字供描红；false = 只给拼音，格子留空默写 */
    val showThemeWords: Boolean = true,
    /** 迷宫纸的随机种子：0 = 每次生成新迷宫，非 0 可复现同一张 */
    val mazeSeed: Long = 0L,
)

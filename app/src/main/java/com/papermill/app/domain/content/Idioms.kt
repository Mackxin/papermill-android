/**
 * 内置成语库。
 *
 * ============================================================
 * 为什么这些内容可以内置
 * ============================================================
 * 成语本身是汉语里的**固定词组**，属于语言事实，任何人都能用；
 * 释义是词典义项的复述，这里全部用**自己的一句话**重写，不抄任何词典、
 * 教辅或网络词条的原句 —— 既不构成侵权，也不会因为别人的错字把我们的题带歪。
 *
 * ============================================================
 * 这个库是要一直变大的
 * ============================================================
 * 加词只要在 [items] 里追加一行 `i("成语", "一句话释义", "主题")`：
 *  - 释义控制在 12~24 字，太长会把选择题选项撑成三行；
 *  - 主题（[tag]）用来挑干扰项：干扰项优先取**不同主题**的释义，
 *    否则「形容高兴」和「形容喜悦」放一个题里，两个都对，题就废了。
 *
 * 题库扩容后「更多 → 内置内容」里的数字会自动跟着变，不用改任何文案。
 */


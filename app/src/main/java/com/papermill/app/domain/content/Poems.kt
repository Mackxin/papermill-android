 * ============================================================
 * 为什么这些诗可以内置
 * ============================================================
 * 这里全部是**唐宋（及少量明清、汉魏）经典诗词原文**，作者距今都在数百年以上，
 * 早已进入公有领域，不存在著作权问题。
 *
 * 但**注释、译文、赏析一律不收录** —— 那些是今人写的，有版权。
 * 本 App 只用到「原文 + 作者 + 朝代」这三样客观信息，
 * 题目里的「这句诗好在写什么」之类提示都是自己现写的白话。
 *
 * ============================================================
 * 这个库也是要一直变大的
 * ============================================================
 * 追加只要在 [items] 里加一首 `p("题目", "作者", "朝代", 年级, "句1", "句2", …)`：
 *  - 每句**带标点**，接句题和选项直接拼，不用再补；
 *  - 句子顺序就是原诗顺序，接句题靠相邻两句出题，顺序错了题就错；
 *  - 只收能确认原文无误的篇目，宁可少收，不要错字。
 */
